#!/usr/bin/env node
// Kit development only (not shipped). Builds the "what is on in each variant" block of README.md from the catalog
// (catalog/options.json) and the profile defaults (templates/scripts/workflow-config.mjs), so the README cannot drift
// from the code. `lib/feature-matrix.test.mjs` fails when the README block differs from this output.
//
//   node scripts/make-feature-matrix.mjs            print the block
//   node scripts/make-feature-matrix.mjs --write    put it in README.md between its markers (inserted before
//                                                   "## Where to go next" the first time)
//
// A variant is a profile (solo, team, org) with or without the factory. Switching the factory on enables
// `skill.run-factory` and everything it requires; those options are locked while the factory is on.

import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTROL_SPECS, PROFILES } from '../templates/scripts/workflow-config.mjs';

const KIT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SUMMARY_START = '<!-- features-summary:start (generated by scripts/make-feature-matrix.mjs; do not edit by hand) -->';
export const SUMMARY_END = '<!-- features-summary:end -->';
export const DOC_START = '<!-- features:start (generated by scripts/make-feature-matrix.mjs; do not edit by hand) -->';
export const DOC_END = '<!-- features:end -->';

export const VARIANTS = [
  { key: 'solo', profile: 'solo', factory: false, label: 'Solo' },
  { key: 'team', profile: 'team', factory: false, label: 'Team' },
  { key: 'org', profile: 'org', factory: false, label: 'Org' },
  { key: 'factorySolo', profile: 'solo', factory: true, label: 'Factory Solo' },
  { key: 'factoryTeam', profile: 'team', factory: true, label: 'Factory Team' },
  { key: 'factoryOrg', profile: 'org', factory: true, label: 'Factory Org' },
];

const readCatalog = () => JSON.parse(readFileSync(join(KIT, 'catalog', 'options.json'), 'utf8'));

const defaultOn = (option, profile) =>
  option.default === true || (typeof option.default === 'object' && option.default !== null && option.default[profile] === true);

/** The options the factory needs: everything `skill.run-factory` requires, directly or not (not the skill itself). */
function factoryClosure(options) {
  const byId = new Map(options.map((option) => [option.id, option]));
  const needed = new Set();
  const queue = [...(byId.get('skill.run-factory')?.requires ?? [])];
  while (queue.length) {
    const id = queue.pop();
    if (needed.has(id) || !byId.has(id) || byId.get(id).kind === 'control') continue;
    needed.add(id);
    queue.push(...(byId.get(id).requires ?? []));
  }
  return needed;
}

/** The control behind a catalog `control.<name>` requirement, shown as its name; other ids stay as they are. */
const needLabel = (id) => (id.startsWith('control.') ? id.slice('control.'.length) : id);

/** Structured data for the matrix: one row per option and per control, with a state for each of the six variants. */
export function buildVariantData() {
  const { options: all } = readCatalog();
  const options = all.filter((option) => option.kind !== 'control');
  const closure = factoryClosure(all);

  const optionRows = options.map((option) => {
    const cells = {};
    for (const variant of VARIANTS) {
      const wanted = defaultOn(option, variant.profile);
      if (variant.factory && closure.has(option.id)) cells[variant.key] = 'locked';
      else if (variant.factory && option.id === 'skill.run-factory') cells[variant.key] = 'on';
      else cells[variant.key] = wanted ? 'on' : 'off';
    }
    return { id: option.id, kind: option.kind, title: option.title, needs: (option.requires ?? []).map(needLabel), cells, since: option.since ?? null };
  });

  const controlRows = Object.entries(CONTROL_SPECS).map(([name, spec]) => {
    const catalogEntry = all.find((entry) => entry.control === name);
    const factoryOnly = name.startsWith('factory.') && name !== 'factory.mode';
    const cells = {};
    for (const variant of VARIANTS) {
      if (name === 'factory.mode') cells[variant.key] = variant.factory ? 'local or pr' : 'off';
      else if (factoryOnly && !variant.factory) cells[variant.key] = '—';
      else cells[variant.key] = String(PROFILES[variant.profile][name]);
    }
    const values = spec.allowed ? spec.allowed.join(' / ') : spec.type === 'boolean' ? 'true / false' : 'a number';
    return { name, title: catalogEntry?.title ?? name, values, env: spec.env, cells };
  });

  return { options: optionRows, controls: controlRows };
}

const SYMBOL = { on: '✅', off: '⬜', locked: '🔒' };
const GROUPS = [
  ['Rules', ['rule']],
  ['Skills', ['skill']],
  ['Hooks and CI', ['hook', 'workflow']],
  ['Review, checks and the factory core', ['agent', 'check']],
  ['Templates and settings', ['template', 'setting']],
  ['Stack packs', ['stack']],
];

function optionTables(rows) {
  const header = `| Feature | ${VARIANTS.map((v) => v.label).join(' | ')} | Needs |\n|---|${VARIANTS.map(() => ':-:').join('|')}|---|`;
  const out = [];
  for (const [group, kinds] of GROUPS) {
    const inGroup = rows.filter((row) => kinds.includes(row.kind));
    if (!inGroup.length) continue;
    out.push(`**${group}**\n\n${header}`);
    for (const row of inGroup) {
      const cells = VARIANTS.map((v) => SYMBOL[row.cells[v.key]]).join(' | ');
      const label = `${row.title} (\`${row.id}\`)${row.since ? ` *new in ${row.since}*` : ''}`;
      out.push(`| ${label} | ${cells} | ${row.needs.map((id) => `\`${id}\``).join(', ') || ' '} |`);
    }
    out.push('');
  }
  return out.join('\n').trimEnd();
}

function controlTable(rows) {
  const lines = [`| Setting (control) | Values | ${VARIANTS.map((v) => v.label).join(' | ')} | Environment variable |`, `|---|---|${VARIANTS.map(() => ':-:').join('|')}|---|`];
  for (const row of rows) {
    lines.push(`| ${row.title} (\`${row.name}\`) | ${row.values} | ${VARIANTS.map((v) => `${row.cells[v.key]}`).join(' | ')} | \`${row.env}\` |`);
  }
  return lines.join('\n');
}

const SAFEGUARDS = [
  'The factory never merges a pull request, deploys, creates or deletes a repository, or force-pushes (the `run-factory` skill\'s "Never" list).',
  '`scripts/factory-guard.mjs push-check` refuses to push `main`, `master` and the remote\'s default branch, in `local` and `pr` mode alike.',
  'The factory builder never commits, pushes or switches branches; only the orchestrator commits, and pushes only in `pr` mode.',
  'Text an agent reads (a file, a log, PR or issue text) is never followed as an instruction, whatever `factory.untrustedText` says: `stop` and `note` differ only in whether the run stops.',
  'The review gate, the docs-fresh check and the reviewer guard fail open: if one cannot run, the work goes through and it says why.',
];

const SUMMARY_SETTINGS = ['planning.gates', 'tests.tdd', 'tests.guard', 'review.mode', 'factory.pushConfirm', 'factory.fastFix', 'factory.untrustedText'];

/** The short block for the README (without the markers): the settings that differ most, and a link to the full list. */
export function generateSummary() {
  const rows = buildVariantData().controls.filter((row) => SUMMARY_SETTINGS.includes(row.name));
  rows.sort((a, b) => SUMMARY_SETTINGS.indexOf(a.name) - SUMMARY_SETTINGS.indexOf(b.name));
  return [
    '## What is on in each variant',
    '',
    'Pick a profile (**Solo**, **Team**, **Org**) and say yes or no to the **factory**: six variants. The settings that differ most are below (— means not used without the factory); you can change every one of them.',
    '',
    `| Setting | ${VARIANTS.map((v) => v.label).join(' | ')} |`,
    `|---|${VARIANTS.map(() => ':-:').join('|')}|`,
    ...rows.map((row) => `| ${row.title} (\`${row.name}\`) | ${VARIANTS.map((v) => row.cells[v.key]).join(' | ')} |`),
    '',
    'Every other feature and setting, which ones the factory turns on and locks, and how to switch each one: **[all features and settings by variant](docs/features.md)**.',
  ].join('\n');
}

/** The full block for docs/features.md (without the markers). */
export function generateFeatureMatrix() {
  const { profiles } = readCatalog();
  const data = buildVariantData();
  const profileRows = profiles.map((p) => `| ${p.name} | ${p.forWho} | ${p.summary} |`);
  const lines = [
    '## What is on in each variant',
    '',
    'A **variant** is a profile (**Solo**, **Team** or **Org**), with or without the **factory** (agents that carry an approved plan through build, checks, review and commit, and in `pr` mode push and open the pull requests; they never merge). The setup asks for the profile first and the factory second.',
    '',
    '| Profile | For | In short |',
    '|---|---|---|',
    ...profileRows,
    '',
    '✅ on by default, you can switch it off · ⬜ off by default, you can switch it on · 🔒 on because the factory needs it, so it cannot be switched off while the factory is on · — does not apply (the factory is off)',
    '',
    '**How you change things.** Every ✅ and ⬜ row is yours to switch. A *feature* (option) is chosen in the setup questions, or later by editing the `enabled` list in `.claude/workspace-kit/choices.json` and running `node .claude/workspace-kit/bin/cli.mjs apply --choices .claude/workspace-kit/choices.json`. A *setting* (control) is changed with `overrides` in `.claude/workflow.json` (for example `"factory.mode": "pr"`), or for one command with the environment variable in the last column (for example `FACTORY_MODE=pr`). The *fixed safeguards* below are not settings.',
    '',
    `<details><summary>Features you can switch on or off (${data.options.length})</summary>`,
    '',
    optionTables(data.options),
    '',
    '</details>',
    '',
    `<details><summary>Settings you can change (${data.controls.length})</summary>`,
    '',
    controlTable(data.controls),
    '',
    '</details>',
    '',
    '<details><summary>Fixed safeguards (no setting turns these off)</summary>',
    '',
    ...SAFEGUARDS.map((text) => `- ${text}`),
    '',
    '</details>',
  ];
  return lines.join('\n');
}

const DOC_HEADER =
  '# Features by variant\n\nGenerated from `catalog/options.json` and the profile defaults by `scripts/make-feature-matrix.mjs` (kit development), so it matches the code. Do not edit between the markers; change the catalog or the generator and run `node scripts/make-feature-matrix.mjs --write`.\n\n';

/** Replaces the block between `start` and `end` in the file, keeping its line endings; `create` makes a missing file or block. */
function writeBlock(file, start, end, block, create) {
  const path = join(KIT, file);
  let original = null;
  try {
    original = readFileSync(path, 'utf8');
  } catch {
    // A missing file is created below, when the caller allows it.
  }
  const eol = original?.includes('\r\n') ? '\r\n' : '\n';
  let text = (original ?? '').replaceAll('\r\n', '\n');
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from !== -1 && to > from) text = text.slice(0, from) + block + text.slice(to + end.length);
  else if (create) text = create(text, block);
  else throw new Error(`${file} has no ${start.slice(0, 24)} markers`);
  writeFileSync(path, eol === '\r\n' ? text.replaceAll('\n', '\r\n') : text);
}

function main(argv) {
  const summary = `${SUMMARY_START}\n${generateSummary()}\n${SUMMARY_END}`;
  const full = `${DOC_START}\n${generateFeatureMatrix()}\n${DOC_END}`;
  if (!argv.includes('--write')) {
    console.log(`${summary}\n\n${full}`);
    return 0;
  }
  try {
    // The README block goes before "## Where to go next" the first time.
    writeBlock('README.md', SUMMARY_START, SUMMARY_END, summary, (text, block) => {
      const anchor = text.indexOf('## Where to go next');
      if (anchor === -1) throw new Error('README.md has no markers and no "## Where to go next" heading to insert before');
      return `${text.slice(0, anchor)}${block}\n\n${text.slice(anchor)}`;
    });
    writeBlock('docs/features.md', DOC_START, DOC_END, full, (text, block) => `${DOC_HEADER}${block}\n`);
  } catch (error) {
    console.error(error.message);
    return 1;
  }
  console.log('README.md and docs/features.md updated');
  return 0;
}

function startedDirectly() {
  try {
    return realpathSync.native(process.argv[1]) === realpathSync.native(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (process.argv[1] && startedDirectly()) process.exit(main(process.argv.slice(2)));
